// TestAppendStamps: turns appended without a time are written after every
// row the file holds, each later than the one before.
func TestAppendStamps(t *testing.T) {
	st, err := Codec.Open(compacted.Home)
	if err != nil {
		t.Fatal(err)
	}
	s, err := st.Read(t.Context(), compactedID)
	if err != nil {
		t.Fatal(err)
	}
	// The file's own time can be older than its rows (a copy that kept an
	// old mtime); new rows must still come after them.
	s.Updated = time.Date(2020, 1, 1, 0, 0, 0, 0, time.UTC)
	s.Entries = append(s.Entries,
		transcript.Entry{Role: transcript.RoleUser, Content: []transcript.Block{{Kind: transcript.BlockText, Text: "again"}}},
		transcript.Entry{Role: transcript.RoleAssistant, Content: []transcript.Block{{Kind: transcript.BlockText, Text: "sure"}}},
	)
	home := t.TempDir()
	dst, err := Codec.Open(home)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := dst.Write(t.Context(), s); err != nil {
		t.Fatal(err)
	}
	fh, err := os.Open(filepath.Join(home, ".claude", "projects", transcript.MangledCwd.Name(compactedCWD), compactedID+".jsonl"))
	if err != nil {
		t.Fatal(err)
	}
	defer fh.Close()
	var stamps []string
	sc := bufio.NewScanner(fh)
	sc.Buffer(nil, 1<<20)
	for sc.Scan() {
		var r struct {
			Timestamp string `json:"timestamp"`
		}
		if json.Unmarshal(sc.Bytes(), &r) == nil && r.Timestamp != "" {
			stamps = append(stamps, r.Timestamp)
		}
	}
	n := len(stamps)
	latest := ""
	for _, ts := range stamps[:n-2] {
		latest = max(latest, ts)
	}
	if !(latest < stamps[n-2] && stamps[n-2] < stamps[n-1]) {
		t.Errorf("appended rows stamped %s, %s after rows up to %s", stamps[n-2], stamps[n-1], latest)
	}
}

// TestRewindToStart: a rewind past the first prompt writes a last-prompt row
// with leafUuid null and explicit:true (Claude Code 2.1.281's rewind path,
// binary only), and Claude resumes with nothing.
func TestRewindToStart(t *testing.T) {
	f := newFixture(t)
	f.prompt(1, 0, "first")
	f.reply(2, 1, "msg_A", text("one"))
	f.raw(map[string]any{"type": "last-prompt", "leafUuid": nil, "explicit": true, "sessionId": fixtureID})
	s := f.read()
	if ctx, lin := s.Context(), s.Linearize(); len(ctx) != 0 || len(lin) != 0 {
		t.Errorf("context %d, linearize %d entries, want none", len(ctx), len(lin))
	}
	// The next prompt starts over, as Claude's would, rather than bringing
	// the rewound history back.
	s.Entries = append(s.Entries, transcript.Entry{Role: transcript.RoleUser, Content: []transcript.Block{{Kind: transcript.BlockText, Text: "again"}}})
	st, err := Codec.Open(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	if _, err := st.Write(t.Context(), s); err != nil {
		t.Fatal(err)
	}
	back, err := st.Read(t.Context(), fixtureID)
	if err != nil {
		t.Fatal(err)
	}
	if lin := back.Linearize(); len(lin) != 1 || lin[0].Text() != "again" {
		t.Errorf("after the rewind, an appended prompt reads back as %d entries", len(lin))
	}
}

