type seen struct {
	role     transcript.Role
	audience transcript.Audience
	text     string
}

func summarize(es []transcript.Entry) []seen {
	out := make([]seen, len(es))
	for i, e := range es {
		text := e.Text()
		if i := strings.IndexByte(text, '\n'); i >= 0 {
			text = text[:i]
		}
		for _, b := range e.Content {
			switch b.Kind {
			case transcript.BlockToolUse:
				text += "[use " + b.ToolID + "]"
			case transcript.BlockToolResult:
				text += "[result " + b.ToolID + "]"
			}
		}
		out[i] = seen{e.Role, e.Audience, text}
	}
	return out
}

func expect(t *testing.T, what string, got []transcript.Entry, want []seen) {
	t.Helper()
	g := summarize(got)
	if len(g) != len(want) {
		t.Errorf("%s: %d entries, want %d", what, len(g), len(want))
	}
	for i := range max(len(g), len(want)) {
		var a, b seen
		if i < len(g) {
			a = g[i]
		}
		if i < len(want) {
			b = want[i]
		}
		if a != b {
			t.Errorf("%s[%d] = %+v, want %+v", what, i, a, b)
		}
	}
}

// TestCompactedResume: the rows /compact kept still name their parents from
// before it, and the boundary has no parent. Claude splices them in behind
// the summary and drops the turn the compaction retired: the model gets the
// summary, the kept turns and the /compact exchange. The retired turn is
// linked in ahead of the boundary, through its logicalParentUuid, so the
// person's view and a move to another agent keep it.
func TestCompactedResume(t *testing.T) {
	st, err := Codec.Open(compacted.Home)
	if err != nil {
		t.Fatal(err)
	}
	s, err := st.Read(t.Context(), compactedID)
	if err != nil {
		t.Fatal(err)
	}
	const (
		summary = "This session is being continued from a previous conversation that ran out of context. The summary below covers the earlier portion of the conversation."
		caveat  = "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>"
		command = "<command-name>/compact</command-name>"
		stdout  = "<local-command-stdout>Compacted (ctrl+o to see full summary)"
		hello   = "Hello from mock server."
		more    = "Tell me more about the project."
		first   = "What is the project codename? Reply ONLY the codename."
	)
	all, model := transcript.AudienceAll, transcript.AudienceModel
	expect(t, "context", s.Context(), []seen{
		{transcript.RoleUser, all, summary},
		{transcript.RoleAssistant, all, hello},
		{transcript.RoleUser, all, more},
		{transcript.RoleAssistant, all, hello},
		{transcript.RoleUser, model, caveat},
		{transcript.RoleUser, all, command},
		{transcript.RoleUser, all, stdout},
	})
	expect(t, "linearize", s.Linearize(), []seen{
		{transcript.RoleUser, all, first},
		{transcript.RoleAssistant, all, "[use toolu_mock_1]"},
		{transcript.RoleTool, all, "[result toolu_mock_1]"},
		{transcript.RoleAssistant, all, hello},
		{transcript.RoleUser, all, more},
		{transcript.RoleAssistant, all, hello},
		{transcript.RoleUser, all, command},
		{transcript.RoleUser, all, stdout},
	})
	// Moved to another agent, the session keeps the summary, the one
	// record of what the compaction retired, and leaves the caveat.
	expect(t, "portable", s.Portable().Lower(transcript.Capabilities{}).Entries, []seen{
		{transcript.RoleUser, all, summary},
		{transcript.RoleAssistant, all, hello},
		{transcript.RoleUser, all, more},
		{transcript.RoleAssistant, all, hello},
		{transcript.RoleUser, all, command},
		{transcript.RoleUser, all, stdout},
	})
	// The chain ends on the attachments the /compact turn left, where the
	// next prompt links.
	if s.Leaf != "e9b82443-fc13-471d-a0ce-695afb159d59" {
		t.Errorf("leaf = %s", s.Leaf)
	}
}

// fixture writes rows as a Claude session file under a fresh home and reads
// it back.
type fixture struct {
	t    *testing.T
	rows []string
	at   time.Time
}

const (
	fixtureCWD = "/tmp/fixture/project"
	fixtureID  = "7d1f7a52-6a44-4d4e-9d7c-0b8a51d5f0a1"
)

func newFixture(t *testing.T) *fixture {
	return &fixture{t: t, at: time.Date(2026, 9, 1, 10, 0, 0, 0, time.UTC)}
}

// uid names fixture row n.
func uid(n int) string { return fmt.Sprintf("00000000-0000-4000-8000-%012d", n) }

// row appends a message row with the fields every Claude row carries.
func (f *fixture) row(typ string, n, parent int, fields map[string]any) {
	f.at = f.at.Add(100 * time.Millisecond)
	r := map[string]any{
		"parentUuid":  nil,
		"isSidechain": false,
		"type":        typ,
		"uuid":        uid(n),
		"timestamp":   f.at.Format("2006-01-02T15:04:05.000Z"),
		"userType":    "external",
		"entrypoint":  "cli",
		"cwd":         fixtureCWD,
		"sessionId":   fixtureID,
		"version":     "2.1.281",
		"gitBranch":   "main",
	}
	if parent > 0 {
		r["parentUuid"] = uid(parent)
	}
	for k, v := range fields {
		r[k] = v
	}
	f.raw(r)
}

func (f *fixture) raw(r map[string]any) {
	b, err := json.Marshal(r)
	if err != nil {
		f.t.Fatal(err)
	}
	f.rows = append(f.rows, string(b))
}

func (f *fixture) prompt(n, parent int, text string) {
	f.row("user", n, parent, map[string]any{"promptId": uid(9000 + n), "message": map[string]any{"role": "user", "content": text}})
}

// reply appends one row of assistant message id, holding the blocks
// Claude's streaming emits for one content_block_stop.
func (f *fixture) reply(n, parent int, id string, blocks ...map[string]any) {
	f.row("assistant", n, parent, map[string]any{
		"requestId": "req_" + id,
		"message": map[string]any{
			"model": "claude-opus-4-6", "id": id, "type": "message", "role": "assistant",
			"content": blocks, "stop_reason": "tool_use", "stop_sequence": nil,
			"usage": map[string]any{"input_tokens": 3, "output_tokens": 12},
		},
	})
}

// result appends a tool result whose parent is the row that made the call,
// as insertMessageChain links it through sourceToolAssistantUUID
// (sessionStorage.ts:1033).
func (f *fixture) result(n, call int, toolID string) {
	f.row("user", n, call, map[string]any{
		"promptId":                uid(9000 + n),
		"message":                 map[string]any{"role": "user", "content": []map[string]any{{"tool_use_id": toolID, "type": "tool_result", "content": "ok " + toolID, "is_error": false}}},
		"toolUseResult":           map[string]any{"stdout": "ok " + toolID},
		"sourceToolAssistantUUID": uid(call),
	})
}

func text(s string) map[string]any { return map[string]any{"type": "text", "text": s} }

func use(id string) map[string]any {
	return map[string]any{"type": "tool_use", "id": id, "name": "Read", "input": map[string]any{"file_path": "/tmp/" + id}}
}

func (f *fixture) lastPrompt(prompt string, leaf int, extra map[string]any) {
	r := map[string]any{"type": "last-prompt", "lastPrompt": prompt, "leafUuid": uid(leaf), "sessionId": fixtureID}
	for k, v := range extra {
		r[k] = v
	}
	f.raw(r)
}

func (f *fixture) read() *transcript.Session {
	f.t.Helper()
	home := f.t.TempDir()
	dir := filepath.Join(home, ".claude", "projects", transcript.MangledCwd.Name(fixtureCWD))
	if err := os.MkdirAll(dir, 0o755); err != nil {
		f.t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, fixtureID+".jsonl"), []byte(strings.Join(f.rows, "\n")+"\n"), 0o644); err != nil {
		f.t.Fatal(err)
	}
	st, err := Codec.Open(home)
	if err != nil {
		f.t.Fatal(err)
	}
	s, err := st.Read(f.t.Context(), fixtureID)
	if err != nil {
		f.t.Fatal(err)
	}
	return s
}

// TestParallelToolCalls: one assistant message with two tool calls is
// written as a row per content block sharing message.id, each chained to
// the one before, and each result hangs off the row of its own call
// (claude.ts emits a message per content_block_stop; the result's parent
// is its sourceToolAssistantUUID). The walk up from the leaf passes through
// the second result only. The mock server behind the harness-test container
// answers with one tool call at a time, so this shape is written by hand
// after real 2.1.x files.
func TestParallelToolCalls(t *testing.T) {
	f := newFixture(t)
	f.prompt(1, 0, "Read a and b.")
	f.reply(2, 1, "msg_A", text("Reading both."))
	f.reply(3, 2, "msg_A", use("toolu_a"))
	f.reply(4, 3, "msg_A", use("toolu_b"))
	f.result(5, 3, "toolu_a")
	f.result(6, 4, "toolu_b")
	f.reply(7, 6, "msg_B", text("Both read."))
	f.lastPrompt("Read a and b.", 7, nil)
	s := f.read()

	all := transcript.AudienceAll
	want := []seen{
		{transcript.RoleUser, all, "Read a and b."},
		{transcript.RoleAssistant, all, "Reading both.[use toolu_a][use toolu_b]"},
		{transcript.RoleTool, all, "[result toolu_a]"},
		{transcript.RoleTool, all, "[result toolu_b]"},
		{transcript.RoleAssistant, all, "Both read."},
	}
	expect(t, "context", s.Context(), want)
	expect(t, "linearize", s.Linearize(), want)
	if s.Leaf != uid(7) {
		t.Errorf("leaf = %s, want %s", s.Leaf, uid(7))
	}
}

